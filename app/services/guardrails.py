"""Guardrails против промпт-инъекций и попыток обойти инструкции модели.

Модуль решает две задачи:
1. Детектирует типичные попытки инъекции («забудь инструкции», «ignore previous
   instructions», «покажи системный промпт» и т.п.).
2. Помогает безопасно обернуть недоверенный ввод пользователя, чтобы модель
   воспринимала его как данные, а не как команды.
"""

